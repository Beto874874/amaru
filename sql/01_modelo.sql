-- ---------------------------------------------------------------------------
-- Catalogos
-- ---------------------------------------------------------------------------

CREATE TABLE departamento (
  id_departamento integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  nombre text NOT NULL,
  CONSTRAINT departamento_nombre_key UNIQUE (nombre),
  CONSTRAINT departamento_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

CREATE TABLE ciudad (
  id_ciudad integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  id_departamento integer NOT NULL,
  nombre text NOT NULL,
  CONSTRAINT ciudad_id_departamento_fkey
    FOREIGN KEY (id_departamento) REFERENCES departamento (id_departamento),
  -- Destino de la FK compuesta de inmueble: garantiza coherencia
  -- ciudad <-> departamento.
  CONSTRAINT ciudad_id_departamento_key UNIQUE (id_ciudad, id_departamento),
  CONSTRAINT ciudad_departamento_nombre_key UNIQUE (id_departamento, nombre),
  CONSTRAINT ciudad_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

CREATE TABLE tipo_inmueble (
  id_tipo integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  nombre text NOT NULL,
  CONSTRAINT tipo_inmueble_nombre_key UNIQUE (nombre),
  CONSTRAINT tipo_inmueble_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

CREATE TABLE contacto (
  id_contacto integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  nombre text NOT NULL,
  telefono text,
  direccion text,
  correo text,
  -- NULLS NOT DISTINCT: dos filas con los mismos cuatro valores (incluidos
  -- los NULL) son el mismo contacto. Evita duplicados al "buscar o crear".
  CONSTRAINT contacto_unico UNIQUE NULLS NOT DISTINCT (nombre, telefono, direccion, correo),
  CONSTRAINT contacto_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

-- ---------------------------------------------------------------------------
-- Inmueble
-- ---------------------------------------------------------------------------

CREATE TABLE inmueble (
  id_inmueble integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  codigo_sae text NOT NULL,
  nombre_inmueble text NOT NULL,
  id_tipo integer NOT NULL,
  id_departamento integer NOT NULL,
  id_ciudad integer,
  id_contacto integer,
  direccion text NOT NULL,
  estrato smallint,
  valor_arriendo bigint,
  area_terreno numeric(12, 2),
  area_construida numeric(12, 2),
  mas_admon boolean NOT NULL DEFAULT false,
  en_home boolean NOT NULL DEFAULT false,
  iva boolean NOT NULL DEFAULT false,
  pagina_web text,
  estado text NOT NULL DEFAULT 'Disponible',
  ubicacion_inferida boolean NOT NULL DEFAULT false,
  alertas text[] NOT NULL DEFAULT '{}',
  fecha_publicacion timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT inmueble_codigo_sae_key UNIQUE (codigo_sae),
  CONSTRAINT inmueble_estrato_check CHECK (estrato BETWEEN 1 AND 6),
  CONSTRAINT inmueble_valor_arriendo_check CHECK (valor_arriendo > 0),
  CONSTRAINT inmueble_areas_check CHECK (
    COALESCE(area_terreno, 0) >= 0 AND COALESCE(area_construida, 0) >= 0
  ),
  CONSTRAINT inmueble_estado_check CHECK (
    estado IN ('Disponible', 'Arrendado', 'No disponible')
  ),

  CONSTRAINT inmueble_id_tipo_fkey
    FOREIGN KEY (id_tipo) REFERENCES tipo_inmueble (id_tipo),
  CONSTRAINT inmueble_id_departamento_fkey
    FOREIGN KEY (id_departamento) REFERENCES departamento (id_departamento),
  -- FK COMPUESTA: la ciudad debe pertenecer al departamento. Si id_ciudad es
  -- NULL la restriccion no se evalua.
  CONSTRAINT inmueble_ciudad_departamento_fkey
    FOREIGN KEY (id_ciudad, id_departamento) REFERENCES ciudad (id_ciudad, id_departamento),
  CONSTRAINT inmueble_id_contacto_fkey
    FOREIGN KEY (id_contacto) REFERENCES contacto (id_contacto)
);

CREATE INDEX inmueble_id_tipo_idx ON inmueble (id_tipo);
CREATE INDEX inmueble_id_departamento_idx ON inmueble (id_departamento);
CREATE INDEX inmueble_id_ciudad_idx ON inmueble (id_ciudad);
CREATE INDEX inmueble_id_contacto_idx ON inmueble (id_contacto);
CREATE INDEX inmueble_estado_idx ON inmueble (estado);
CREATE INDEX inmueble_valor_arriendo_idx ON inmueble (valor_arriendo);

-- ---------------------------------------------------------------------------
-- Trigger generico de updated_at (lo usan inmueble y usuario)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER inmueble_set_updated_at
BEFORE UPDATE ON inmueble
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

